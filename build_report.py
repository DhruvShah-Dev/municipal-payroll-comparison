"""Build the canonical portable report input from analyze.py's reviewed aggregates."""

import csv
import json
import sqlite3
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "data"
summary = list(csv.DictReader((DATA / "city_year_summary.csv").open(encoding="utf-8")))
departments = list(csv.DictReader((DATA / "department_2025.csv").open(encoding="utf-8")))
metadata = json.loads((DATA / "run_metadata.json").read_text(encoding="utf-8"))
db = sqlite3.connect(":memory:")
db.row_factory = sqlite3.Row
for table, rows in (("city_year_summary", summary), ("department_2025", departments)):
    columns = list(rows[0])
    db.execute(f"CREATE TABLE {table} ({', '.join(name + ' TEXT' for name in columns)})")
    db.executemany(f"INSERT INTO {table} VALUES ({', '.join('?' for _ in columns)})",
                   ([row[name] for name in columns] for row in rows))

service_names = {
    "Chicago": {"Police": "D57 - Chicago Police Department", "Fire": "D59 - Chicago Fire Department"},
    "New York City": {"Police": "POLICE DEPARTMENT", "Fire": "FIRE DEPARTMENT"},
    "San Francisco": {"Police": "Police", "Fire": "Fire Department"},
}
db.execute("CREATE TABLE service_map (city TEXT, service TEXT, department TEXT)")
for city, names in service_names.items():
    for service, name in names.items():
        db.execute("INSERT INTO service_map VALUES (?,?,?)", (city, service, name))
city_sql = (ROOT / "queries" / "city_year.sql").read_text(encoding="utf-8")
service_sql = (ROOT / "queries" / "service_share.sql").read_text(encoding="utf-8")
chart_rows = [dict(row) for row in db.execute(city_sql)]
share_rows = [dict(row) for row in db.execute(service_sql)]
assert len(chart_rows) == 6 and len(share_rows) == 6

